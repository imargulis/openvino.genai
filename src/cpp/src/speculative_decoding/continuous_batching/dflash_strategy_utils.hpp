// Largest seed + mask block a request may draft; bounds the extra batch budget of the draft scheduler.
inline constexpr size_t MAX_DRAFT_BLOCK_ROWS = 32;

// Per-request state of the DFlash draft pipeline.
struct DraftState {
    // Request ids are reused across generate() calls; the sequence id identifies the request.
    uint64_t sequence_id = 0;
    // Leading positions whose draft KV was built from target hidden states.
    size_t committed_rows = 0;
    // Target hidden-state rows [rows, 1, hidden] after the committed positions, not yet forwarded.
    // It may view the target's output tensor until it is owned.
    ov::Tensor pending_rows;
    bool owns_pending_rows = false;
    size_t block_rows = 0;
    size_t candidate_rows = 0;
    // Draws the candidates of a sampled request from its Top-K candidate lattice, seeded with the draft request's seed.
    std::mt19937 lattice_rng;
};

// The rows of one request's forwarded draft block in the draft outputs, which hold the gathered rows of all
// blocks of a step one block after another.
struct DraftBlockRows {
    // the token before the first candidate, the seed
    int64_t anchor_token = 0;
    size_t first_row = 0;
    size_t num_rows = 0;
    // the leading rows the target validates, at most num_rows
    size_t num_candidates = 0;
};

inline void ensure_vlm_generation_config(const GenerationConfig& config) {
    // These checks cover only VLM representation/output modes that cannot be expressed faithfully with
    // row-aligned multimodal prompt IDs.
    OPENVINO_ASSERT(config.pruning_ratio == 0,
                    "DFlash VLM does not support visual token pruning.");
    OPENVINO_ASSERT(!config.echo && config.logprobs == 0,
                    "DFlash VLM does not support echo or prompt logprobs for row-aligned multimodal prompt IDs.");
    OPENVINO_ASSERT(!config.return_omni_outputs,
                    "DFlash VLM does not support Omni intermediate outputs.");
}

// Rows of the seed + mask block for `candidate_count` drafted tokens.
inline size_t draft_block_length(size_t candidate_count, size_t candidate_position_offset) {
    OPENVINO_ASSERT(candidate_count > 0, "DFlash candidate_count must be greater than 0.");
    return candidate_count + candidate_position_offset;
}

// A draft step forwards, per request, the target rows of the previous target step plus one block.
inline size_t draft_max_num_batched_tokens(size_t main_max_num_batched_tokens, size_t max_num_seqs) {
    const size_t limit = std::numeric_limits<size_t>::max();
    const size_t block_budget = max_num_seqs > limit / MAX_DRAFT_BLOCK_ROWS ? limit : max_num_seqs * MAX_DRAFT_BLOCK_ROWS;
    return main_max_num_batched_tokens > limit - block_budget ? limit : main_max_num_batched_tokens + block_budget;
}

inline size_t draft_candidate_count(size_t num_assistant_tokens, size_t generated_len, size_t max_new_tokens) {
    OPENVINO_ASSERT(num_assistant_tokens > 0, "DFlash num_assistant_tokens must be greater than 0.");
    if (generated_len >= max_new_tokens) {
        return 0;
    }
    return num_assistant_tokens;
}

// Candidates the target can still validate: the last token is always generated by the target.
inline size_t validation_candidate_count(size_t draft_count, size_t generated_len, size_t max_new_tokens) {
    if (generated_len >= max_new_tokens) {
        return 0;
    }
    const size_t remaining = max_new_tokens - generated_len;
    if (remaining <= 1) {
        return 0;
    }
    return std::min(draft_count, remaining - 1);
}

struct DraftRowSelection {
    size_t begin = 0;
    size_t count = 0;
};

// Rows of the target's exported hidden states that the draft has not seen yet. The exported rows end at
// the target's processed length, followed by the rows of the rejected candidates; a validation window that the
// token budget split leaves its last candidates without rows. A target that recomputes preempted tokens replays
// rows the draft has already seen.
inline DraftRowSelection select_new_target_rows(uint64_t request_id,
                                                size_t known_rows,
                                                size_t target_rows,
                                                size_t hidden_rows,
                                                size_t rejected_candidates) {
    if (target_rows <= known_rows) {
        return {};
    }
    const size_t new_rows = target_rows - known_rows;
    OPENVINO_ASSERT(hidden_rows >= new_rows,
                    "DFlash target exported ", hidden_rows, " hidden-state rows for request ", request_id,
                    ", but the draft needs ", new_rows, ".");
    const size_t rejected_rows = std::min(rejected_candidates, hidden_rows - new_rows);
    return {hidden_rows - rejected_rows - new_rows, new_rows};
}

struct DraftBlockPlan {
    size_t block_rows = 0;
    size_t candidate_rows = 0;
};

// A block is drafted once the draft knows the target hidden states up to the token before the seed,
// the last generated token. The block keeps its full size while fewer candidates are validated near
// max_new_tokens.
inline DraftBlockPlan plan_draft_block(size_t num_assistant_tokens,
                                       size_t generated_len,
                                       size_t max_new_tokens,
                                       size_t prompt_len,
                                       size_t known_rows,
                                       size_t candidate_position_offset) {
    if (num_assistant_tokens == 0 || generated_len == 0 || known_rows != prompt_len + generated_len - 1) {
        return {};
    }
    const size_t draft_count = draft_candidate_count(num_assistant_tokens, generated_len, max_new_tokens);
    const size_t candidate_rows =
        draft_count > 0 ? validation_candidate_count(draft_count, generated_len, max_new_tokens) : 0;
    if (candidate_rows == 0) {
        return {};
    }
    return {draft_block_length(draft_count, candidate_position_offset), candidate_rows};
}

// The candidate scorer takes the rows of num_blocks draft blocks packed back to back: block n spans rows
// subsequence_begins[n] to subsequence_begins[n + 1]. The graph marks the first row of every block and gives it the
// block's anchor as predecessor, so an empty block would mark a row twice and shift the anchors of later blocks.
inline void validate_subsequence_begins(const ov::Tensor& subsequence_begins, size_t num_blocks, size_t num_rows) {
    OPENVINO_ASSERT(num_blocks > 0, "The candidate scorer needs at least one draft block.");
    OPENVINO_ASSERT(subsequence_begins && subsequence_begins.get_element_type() == ov::element::i64 &&
                        subsequence_begins.get_shape() == ov::Shape{num_blocks + 1},
                    "The candidate scorer subsequence_begins must be an I64 tensor of shape [",
                    num_blocks + 1,
                    "].");
    const auto* begins = subsequence_begins.data<const int64_t>();
    OPENVINO_ASSERT(begins[0] == 0 && begins[num_blocks] == static_cast<int64_t>(num_rows),
                    "The candidate scorer subsequence_begins must start at 0 and end at the number of draft rows ",
                    num_rows,
                    ".");
    for (size_t block = 0; block < num_blocks; ++block) {
        OPENVINO_ASSERT(begins[block] < begins[block + 1],
                        "The candidate scorer subsequence_begins must be strictly increasing: draft block ",
                        block,
                        " is empty.");
    }
}

// The candidate scorer returns a Top-K lattice over the packed rows of all draft blocks:
//   candidate_ids [rows, K]: the backbone's K best tokens at every row;
//   edge_scores [rows, K, K]: edge_scores[s, i, j] scores candidate j at row s after candidate i at row s - 1.
// The first row of a block follows the block's anchor instead, so edge_scores[s, i, :] is the same for every i there.
inline void validate_candidate_lattice(const ov::Tensor& edge_scores,
                                       const ov::Tensor& candidate_ids,
                                       size_t num_positions,
                                       size_t vocab_size) {
    OPENVINO_ASSERT(candidate_ids && candidate_ids.get_element_type() == ov::element::i64 &&
                        candidate_ids.get_shape().size() == 2 && candidate_ids.get_shape()[0] == num_positions &&
                        candidate_ids.get_shape()[1] > 0,
                    "Candidate scorer candidate_ids must be an I64 tensor of shape [",
                    num_positions,
                    ", K].");
    const size_t top_k = candidate_ids.get_shape()[1];
    OPENVINO_ASSERT(edge_scores && edge_scores.get_element_type() == ov::element::f32 &&
                        edge_scores.get_shape() == ov::Shape({num_positions, top_k, top_k}),
                    "Candidate scorer edge_scores must be an FP32 tensor of shape [",
                    num_positions,
                    ", ",
                    top_k,
                    ", ",
                    top_k,
                    "].");
    const auto* ids = candidate_ids.data<const int64_t>();
    OPENVINO_ASSERT(std::all_of(ids,
                                ids + candidate_ids.get_size(),
                                [&](int64_t id) {
                                    return id >= 0 && static_cast<size_t>(id) < vocab_size;
                                }),
                    "Candidate scorer candidate_ids must be draft vocabulary ids.");
}

// Walks the lattice rows [first_row, first_row + num_positions) of one block greedily: at every position, the best
// candidate in the row of the candidate drafted before it. Ties go to the smaller token id, as in a greedy scan over
// the vocabulary. A row's scores depend on that row and its predecessor only, so a walk over the leading positions of
// a block drafts the leading tokens of a walk over the whole block.
inline std::vector<int64_t> greedy_candidate_path(const ov::Tensor& edge_scores,
                                                  const ov::Tensor& candidate_ids,
                                                  size_t first_row,
                                                  size_t num_positions) {
    const size_t top_k = candidate_ids.get_shape()[1];
    OPENVINO_ASSERT(first_row + num_positions <= candidate_ids.get_shape()[0],
                    "The candidate path exceeds the rows of the candidate lattice.");
    const auto* scores = edge_scores.data<const float>();
    std::vector<int64_t> path;
    path.reserve(num_positions);
    size_t previous_index = 0;
    for (size_t position = first_row; position < first_row + num_positions; ++position) {
        const auto* row = scores + (position * top_k + previous_index) * top_k;
        const auto* ids = candidate_ids.data<const int64_t>() + position * top_k;
        size_t best = 0;
        for (size_t j = 1; j < top_k; ++j) {
            if (row[j] > row[best] || (row[j] == row[best] && ids[j] < ids[best])) {
                best = j;
            }
        }
        previous_index = best;
        path.push_back(ids[best]);
    }
    return path;
}

// True when the logit processors of a draft sampler with this config cannot change which token has the highest logit,
// so a greedy draft can take the best token of every row without the sampler. Follows the transforms that
// LogitProcessor adds for greedy decoding; the log-prob transforms keep the argmax.
inline bool logit_processors_keep_argmax(const GenerationConfig& config) {
    return config.is_greedy_decoding() && config.repetition_penalty == 1.0f && config.presence_penalty == 0.0f &&
           config.frequency_penalty == 0.0f && config.min_new_tokens == 0 && !config.is_structured_output_generation();
}

// Tokens outside the candidates are shifted at least this far below the worst candidate.
inline constexpr float CANDIDATE_ROW_GAP = 1.0e4f;

// Spreads the lattice row at `position` that follows candidate previous_index at position - 1 over the vocabulary, so
// the request's logit processors and sampler pick the token as they do from a full logits row. Candidate j gets
// edge_scores[position, previous_index, j]. Every other token keeps its backbone logit, shifted below the candidates
// by at least CANDIDATE_ROW_GAP: a candidate still wins after the usual penalties unless the processors mask all K of
// them, and then the token comes from the remaining backbone logits. A repetition_penalty far below 1 can lift a
// non-candidate above the candidates, as it would with the dense Markov step, and the walk then ends the block at
// that token.
inline void fill_candidate_row(const float* backbone_logits,
                               size_t vocab_size,
                               const ov::Tensor& edge_scores,
                               const ov::Tensor& candidate_ids,
                               size_t position,
                               size_t previous_index,
                               float* row) {
    const size_t top_k = candidate_ids.get_shape()[1];
    const auto* ids = candidate_ids.data<const int64_t>() + position * top_k;
    const auto* scores = edge_scores.data<const float>() + (position * top_k + previous_index) * top_k;
    // The candidates are the backbone's Top-K at this position, so its best logit is among them.
    float best_logit = -std::numeric_limits<float>::infinity();
    float worst_score = std::numeric_limits<float>::infinity();
    for (size_t j = 0; j < top_k; ++j) {
        best_logit = std::max(best_logit, backbone_logits[ids[j]]);
        worst_score = std::min(worst_score, scores[j]);
    }
    const float shift = worst_score - CANDIDATE_ROW_GAP - best_logit;
    std::transform(backbone_logits, backbone_logits + vocab_size, row, [shift](float logit) {
        return logit + shift;
    });
    for (size_t j = 0; j < top_k; ++j) {
        row[ids[j]] = scores[j];
    }
}

inline std::optional<size_t> find_candidate(const ov::Tensor& candidate_ids, size_t position, int64_t token_id) {
    const size_t top_k = candidate_ids.get_shape()[1];
    const auto* ids = candidate_ids.data<const int64_t>() + position * top_k;
    const auto* found = std::find(ids, ids + top_k, token_id);
    if (found == ids + top_k) {
        return std::nullopt;
    }
    return static_cast<size_t>(std::distance(ids, found));
}

// Walks the lattice rows [first_row, first_row + num_positions) of one block through a sampler. At every position,
// sample_token(position, previous_index) draws a token from the lattice row that follows candidate previous_index at
// the position before, spread over the vocabulary by fill_candidate_row(), and returns it, or nullopt to end the
// block. A token outside the position's candidates ends the block as well, since the lattice has no row for it.
template <typename SampleToken>
void walk_candidate_lattice(const ov::Tensor& candidate_ids,
                            size_t first_row,
                            size_t num_positions,
                            SampleToken&& sample_token) {
    OPENVINO_ASSERT(first_row + num_positions <= candidate_ids.get_shape()[0],
                    "The candidate walk exceeds the rows of the candidate lattice.");
    size_t previous_index = 0;
    for (size_t position = first_row; position < first_row + num_positions; ++position) {
        const std::optional<int64_t> token = sample_token(position, previous_index);
        if (!token) {
            return;
        }
        const auto index = find_candidate(candidate_ids, position, *token);
        if (!index) {
            return;
        }
        previous_index = *index;
    }
}

struct SampledCandidate {
    int64_t token = 0;
    float log_prob = 0.0f;
    DraftProposalPtr proposal;
};

// Draws the candidates of the lattice rows [first_row, first_row + num_positions) of one block: every position from
// the softmax, at `temperature`, of the row that follows the candidate drafted before it. Each candidate carries that
// distribution over the row's K candidates, which the target verifies it against.
inline std::vector<SampledCandidate> sample_candidate_path(const ov::Tensor& edge_scores,
                                                           const ov::Tensor& candidate_ids,
                                                           size_t first_row,
                                                           size_t num_positions,
                                                           float temperature,
                                                           std::mt19937& rng) {
    OPENVINO_ASSERT(temperature > 0.0f, "Sampled DFlash drafts with a Markov head require temperature > 0.");
    OPENVINO_ASSERT(first_row + num_positions <= candidate_ids.get_shape()[0],
                    "The candidate path exceeds the rows of the candidate lattice.");
    const size_t top_k = candidate_ids.get_shape()[1];
    const auto* scores = edge_scores.data<const float>();
    const auto* ids = candidate_ids.data<const int64_t>();
    std::vector<SampledCandidate> candidates;
    candidates.reserve(num_positions);
    size_t previous_index = 0;
    for (size_t position = first_row; position < first_row + num_positions; ++position) {
        const auto* row = scores + (position * top_k + previous_index) * top_k;
        const float max_score = *std::max_element(row, row + top_k);
        DraftProposal proposal;
        proposal.token_ids.assign(ids + position * top_k, ids + (position + 1) * top_k);
        proposal.probabilities.resize(top_k);
        float probability_sum = 0.0f;
        for (size_t index = 0; index < top_k; ++index) {
            proposal.probabilities[index] = std::exp((row[index] - max_score) / temperature);
            probability_sum += proposal.probabilities[index];
        }
        OPENVINO_ASSERT(probability_sum > 0.0f && std::isfinite(probability_sum),
                        "The DFlash candidate lattice produced an invalid proposal distribution.");
        for (auto& probability : proposal.probabilities) {
            probability /= probability_sum;
        }
        std::discrete_distribution<size_t> distribution(proposal.probabilities.begin(), proposal.probabilities.end());
        const size_t selected = distribution(rng);
        candidates.push_back({proposal.token_ids[selected],
                              std::log(proposal.probabilities[selected]),
                              std::make_shared<const DraftProposal>(std::move(proposal))});
        previous_index = selected;
    }
    return candidates;
}

